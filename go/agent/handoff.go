package agent

import (
	"fmt"
	"strings"
)

// handoff —— 把一件事交办给同屋的人.
//
// ── 为什么需要它 ──
//
// 能由同屋进程完成的工作应当交给它处理.
//
// 房间是**单向**的: 新输入到达时客户端只捎带上"进程没听到的那几句"
// (roomContext.ts), 除此之外没有任何东西能让一个 bot 动起来. 于是
// 领头的那个只能说"这块该让小登去做" —— 然后停在那儿等用户去转达.
// 判断是它做的, 跑腿还是用户的.
//
// ── 为什么必须有界 ──
//
// roomContext.ts 里写着这套东西最怕的事: 把每个人的发言都投进别人的
// 收件箱, 等于每句话触发 N-1 次新回合, 而那些回合又各自触发下一轮 ——
// **一屋子 bot 会自己聊到预算烧光**. handoff 正是在开这个口子.
//
// 所以只开一层: **只有用户开的头能派活, 被交办的人不能再往下转**.
// 一句用户输入最多多出"屋里人数减一"个回合, 到此为止 —— 链子长不了,
// 因为根本没有第二节. 这比"限制深度到 N"简单, 也比它好解释:
// 一次输入最多让屋里每个进程动一次.
//
// ── 为什么不等结果 ──
//
// 让派活的那个等着收结果, 就得在它这一轮里再起一个回合, 而那个回合
// 结束又要唤醒它 —— 链子从"一层"变回"不知道几层". 交办完就返回,
// 干活的人把结果说在房间里, 界面直接展示. 派活的那个下次输入到达时
// 通过房间上下文知道结果, 跟人在群里干活是一样的.

/**
 * handoffMost 一句交代最多多长.
 *
 *	不是"长了不好看": 超过这个长度的内容无一例外是**把该落进
 *	文件的东西抄进了一句话**(见 runHandoff 里那段). 人交代一件事很少
 *	用得上三百个字.
 */
/**
 * handoffMost 一句交代最多多长.
 *
 *	**按一条合格交代的实际内容定, 不是按"多长算长"定**:
 *
 *	    登录页归你，接口按 CHARTER.md，别动 backend/。     30 字
 *	    后端你来，按 CHARTER.md 的契约，零依赖。           22 字
 *
 *	三百字那一版仍然是在指挥怎么做:
 *
 *	    index.html（表单：用户名、密码、登录按钮 + 一个结果提示区）、
 *	    app.js、style.css…… app.js 表单提交时用 fetch 调 POST
 *	    '/api/login'（相对路径、同源），body 是 JSON {username,password}
 *
 *	一百五十字放不下一份规格书, 而"这块归谁 + 要什么 + 别碰哪儿"够用得多
 *	—— 那三样正是派活的人该说的全部.
 */
const handoffMost = 150

/**
 * teaching 这句交代里有没有在教同行怎么干活 —— 有就把那处指出来.
 *
 *	**只认工具名和流程话**: 它们出现在交办里几乎必然是多余的(对方自己
 *	会), 而且好认、不会冤枉人. 技术选型那类("别用框架")没法这么判 ——
 *	与其瞎猜, 不如只挡这几处确凿的.
 */
func teaching(task string) string {
	for _, sign := range []string{"sync_down", "merge_up", "hand_over", "handoff"} {
		if strings.Contains(task, sign) {
			return sign
		}
	}
	return ""
}

// HandoffTool 把活交办给同屋的人. pass 为 nil 时不挂这个工具 ——
// 不承诺做不到的事.
func HandoffTool(pass func(who, task string) (string, error)) Tool {
	return Tool{
		Name: "handoff",
		// 声明只说"是什么" —— 判断和细节全在工具的错误文本里:
		// 那份在出错那一刻才付, 而这几行是**每一轮都付**.
		// (名字写错了会列出屋里有谁; 交代太短会当场退回.)
		Desc: "交办给同屋的人",
		Args: map[string]string{
			"who": "交给谁",
			// 上限要写在脸上: 不写的话模型每次第一把都按直觉写 160 字,
			// 必然触发闸门并重试 —— 交办会白烧一轮.
			// "错误文本里才说细节"的规矩对**必然发生**的错不成立: 预防更便宜.
			"task": "**只说要什么, 150 字以内** —— 别写他的身份和步骤, 他跟你一样会看项目、会自己验、会合上去",
		},
		ArgOrder: []string{"who", "task"},
		Mutates:  true,
		Run: func(t Toolbox, a map[string]any) (string, error) {
			return runHandoff(t, a, pass)
		},
	}
}

func runHandoff(t Toolbox, a map[string]any, pass func(who, task string) (string, error)) (string, error) {
	who := strings.TrimSpace(argStr(a, "who"))
	task := strings.TrimSpace(argStr(a, "task"))
	if who == "" {
		return "", fmt.Errorf("没说交给谁")
	}
	// **转包到此为止**. 见上面"为什么必须有界".
	//
	// 这条拦在最前面: 参数对不对都不重要了, 这一轮本来就不该派活.
	if t.Relayed {
		// blockedf 不是 Errorf: 这是闸**按设计**挡的, 不是干活失败.
		// 界面上"1 个没成"会让用户去查一个不存在的故障 —— 见 blocked.go.
		return "", blockedf("%s", "这件事是同屋交办给你的, **你自己做完** —— "+
			"再往下转会没完没了。做不了就说做不了, 那句话会回到用户眼前")
	}
	// **说不清要什么就别交**: 他看不见你们的对话, 收到一句"帮我看看那个"
	// 只能反问, 而反问是问到用户脸上的 —— 等于你把活推给了他, 他把活
	// 推回给了用户
	if task == "" {
		return "", fmt.Errorf("没说让「%s」干什么。他看不见你们的对话, "+
			"要什么结果得写在这句话里", who)
	}
	if len([]rune(task)) < 6 {
		return "", fmt.Errorf("交代得太短了(%q)。他没有上下文, 照这句话干不出你要的东西", task)
	}
	/**
	 * **交代得太长也要退回去**.
	 *
	 * ── 典型的错误形态 ──
	 *
	 *	小丁给小戊派后端, 写了 902 个字: 端口读哪个环境变量、静态文件
	 *	怎么托管、POST /api/login 解析失败返回什么状态码、成功返回的
	 *	JSON 里有哪几个字段、演示账号叫什么…… 一份规格书.
	 *
	 * ── 为什么这是个毛病, 而不是"认真" ──
	 *
	 *	**那些细节是它猜的**. 它自己一行后端都没写过, 却把状态码和
	 *	JSON 形状全定死了 —— 接手的人照着做, 做出来的是"小丁想象中的
	 *	后端", 而不是对的那个.
	 *
	 *	**而且项目里就有一份**. CHARTER.md / API.md 是两个人都看得见、
	 *	改了还能同步的东西. 抄进一句话里的那份, 从抄完那一刻就开始过期.
	 *
	 *	**人也不这么说话**. 人会说"你做后端, 接口按 API.md 来".
	 *
	 * ── 为什么是退回而不是截断 ──
	 *
	 *	截断会把最后几条要求悄悄吃掉, 而它以为都说了. 退回去让它自己
	 *	重说一句, 顺便把该落进文件的东西落进文件.
	 */
	/**
	 * **别教同行怎么干活**.
	 *
	 * ── 用户看着两条交办说的话 ──
	 *
	 *	"竟然还需要说契约 agent 是干啥的…还说这么详细…那还是团队协作吗,
	 *	我来指挥得了呗"
	 *
	 *	他说的是这两句里的这些东西:
	 *
	 *	  先 sync_down 拉到          —— 教同行用工具
	 *	  完成后自己跑一遍再 merge_up  —— 叮嘱同行要自测、要交活
	 *	  契约在 CHARTER.md 里        —— 解释项目里的文件是什么
	 *	  监听 3000 端口, 别用框架     —— 连怎么做都替他定了
	 *
	 *	**每个 bot 受的是同一套规矩**: 拉主干、自己验、合上去, 它自己的
	 *	提示词里都写着. 派活的那个之所以要重复一遍, 是因为它不知道这件事.
	 *
	 *	而这么写的代价不只是啰嗦: 接手的人被降成一双手, 他那份判断力
	 *	白买了 —— 那时候确实"人自己指挥得了".
	 */
	if bossy := teaching(task); bossy != "" {
		return "", fmt.Errorf("这句话里在教他怎么干活(%s)。**他跟你受的是同一套规矩** —— "+
			"拉主干、自己验、合上去都不用你说。只说这块归他、你要什么结果; "+
			"怎么做是他的判断, 那正是找他来的原因", bossy)
	}
	if n := len([]rune(task)); n > handoffMost {
		return "", fmt.Errorf("这段交代 %d 个字, 那是规格书不是交代活。**只说三样**: "+
			"这块归他、你要什么结果、别碰哪儿。怎么做是他的判断; 细节写进 CHARTER.md "+
			"(他看得见, 改了还能同步), 抄进这句话的那份从抄完就开始过期", n)
	}
	if pass == nil {
		return "", fmt.Errorf("这个环境里没有房间, 交办不了 —— 自己干或者告诉用户")
	}
	detail, err := pass(who, task)
	if err != nil {
		return "", err
	}
	/**
	 * **这句话由工具自己接上, 不交给宿主**.
	 *
	 *	不接的话它会说"我盯着他, 做完告诉你" —— 而这条路上
	 *	没有任何东西会把结果送回来(见上面"为什么不等结果").
	 *	一句它做不到的承诺, 用户就坐在那儿等一个永远不来的汇报.
	 *
	 *	放在这儿而不是宿主里: 换个宿主接同一个工具, 这句话不该丢.
	 */
	return okResult("success", detail+"\n"+
		"**你收不到他的回复** —— 他干完直接在房间里说, 用户看得见。"+
		"你这一轮该说什么说什么, 别说你会盯着他。"), nil
}
