package agent

import (
	"strings"
	"testing"
)

/**
 * **需求不清楚的时候, 先看能不能自己定** —— 而不是停下来等人挑.
 *
 * ── 这个约束针对的失败模式 ──
 *
 *	三个人做完一个登录页之后, 输入"在刚才那个东西上再加一块：
 *	能按关键字搜". 小己回了一大段: 搜什么？数据从哪来？要不要登录后可见？
 *	最后一句是 **"你定个方向，我再动手——先不写代码"**.
 *
 *	它没做错任何事: 需求确实模糊, 它把选择摆清楚了, 还给了推荐(走 A).
 *	可自动执行环境中的前提是**人可能已经走开了** —— 一个问题换来的不是
 *	一次澄清, 是几个小时的空转. 而它自己都说了"我的建议是走 A".
 *
 *	所以规矩要反过来: 心里有明显更合适的那个选择, 就按它做一版最小的,
 *	把选择连同做了什么一起说. 只有**做错了收不回来**才值得先问.
 */
func Test需求不清楚时先做默认而不是先反问(t *testing.T) {
	// 它得知道"自己定"是常态
	for _, want := range []string{"自己定", "别停下来等他挑"} {
		if !strings.Contains(layerTriage, want) {
			t.Errorf("提示词里没有这条: %q", want)
		}
	}
	// 而"先反问"不该再是缺省
	if strings.Contains(layerTriage, "先反问清楚") {
		t.Error("还写着「先反问清楚」—— 那会让它在人走开之后停一整夜")
	}
	// 但也不能变成"什么都不问": 收不回来的还是要问
	if !strings.Contains(layerTriage, "收不回来") {
		t.Error("没留下「该问的时候要问」那条口子")
	}
}
