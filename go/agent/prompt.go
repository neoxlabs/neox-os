const layerAutonomy = `## 自主执行

- **下令的事直接做完，不要二次确认。** 读写文件、跑测试跑编译都在你范围内，越界系统会拦。做完报告结果，别反问"需要我……吗？"
- **不可逆的动作先说一声**：删文件、清空目录、丢弃未提交的改动、覆盖用户没让你动的东西。这类命令**内核不会拦你**（它们都在授权范围内），所以判断只能靠你。说清楚要动什么，等他一句话。
- **不要在收尾时用反问扩大范围。** 改完一个文件不要问"要不要顺便优化下别的"，可选的后续用一句陈述带过。
- **被纠正时直接按纠正做，给出结果。** 不要"你说得对""抱歉我疏忽了"——行动本身就是回应。`

// ── 层 5: 怎么想 ────────────────────────────────────────────
//
// 这一层是整份提示词的核心, 也是"给思路不给剧本"最吃紧的地方.
//
// 它合并了原来的"怎么找信息"和"判断力"两层. 那两层本来就在讲同一件事 ——
// **怎么用最少的动作拿到最硬的证据** —— 拆开之后各自都长出了一堆
// 工具用法细节(某个模式要以两个星号开头之类), 那些是工具描述和错误文本
// 该说的, 不是思路.
//
// 保留的都是**跨场景成立**的判断方式, 每一条背后都有一次真机失败:
//
//	拿最直接的证据    它读源码猜测试过不过, 而跑一次测试就有答案
//	search 优先       1001 行的日志分三片整读, prompt 涨到 8485 token
//	不猜相同性        拿文件名当"重复"的证据, 而用户照着这个判断删文件
//	两次失败换假设    同一个坑里第三次
//	结论当场落地      原文会被折叠腾掉, 写下的结论不会

// **搜索那一条必须跟着工具表走, 不能写死在正文里.**
//
// 写死的话, 没配搜索的机器上提示词照样写着"先 web_search" —— 而工具表里
// 根本没有它. 模型会照着调, 拿到一句"没有这个工具", 而它没有任何线索
// 可以自纠: **提示词说有它就信**.
// (这是 TestPromptMentionsOnlyRealTools 当场抓出来的, 第一版就是写死的.)
//
// **前缀仍然稳定**: 工具表在进程启动时定死, 同一段对话里逐字节不变 ——
// 跟 writable / recent 是同一类的环境事实.
func layerThinking(ts *ToolSet) string {
	extra := ""
	if _, ok := ts.Get("web_search"); ok {
		extra += searchLine
	}
	if _, ok := ts.Get("recall"); ok {
		extra += recallLine
	}
	if _, ok := ts.Get("show"); ok {
		extra += showLine
	}
	return thinkingHead + extra + thinkingTail
}

