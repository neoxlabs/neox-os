package agent

import "strings"

// 精简提示词 —— **一套，不是两套**.
//
// ── 为什么重写 ──
//
//	原来那份 11888 字节 + 7228 字节工具声明 = 20894, 每一轮都付.
//	而账本里跑着的是一个**生活助理**, 它每轮读的却是: PLAN.md/CHARTER.md
//	怎么维护、git worktree 分支规矩、出网授权怎么申请、"完成条件"1711 字节、
//	"读工具结果""动手时" —— 对"5:30 提醒我打卡"一个字都用不上.
//
//	多一条规矩就是多一样能让它分心的东西. 在 29 个工具里有四个都是
//	"以后提醒我"(remind_me/check_every/when/watch_for), 于是它给同一件事
//	建了三条重复的巡检, 每 10 分钟醒一次只为回一句"（非窗口期，不动。）".
//
// ── 删掉的那些去哪儿了 ──
//
//	**沉到工具说明里**. "run 第一行是退出码""改文件前先读一遍""write_file
//	是整体覆盖" —— 这些是**某个工具**的用法, 不是跨场景的判断方式.
//	写在工具说明里跟着工具表走: 这台机器没挂那个工具, 那句话就不出现.
//
//	真正跨场景的只剩三件: 你是谁、边界在哪、怎么说话.
//
// ── 为什么敢删 ──
//
//	现在的模型已经把 agent 行为 RL 进去了. "打招呼不要去翻目录""改完要
//	验一遍""别猜文件存不存在" —— 这些不用教, 教了是在跟它已经会的东西
//	抢注意力.
//
//	但**不能靠感觉**: 账本里 67 条真人对话是基准集, 改前改后各跑一遍,
//	比步数/耗时/token/回复字数, 外加逐条判"简要·合理·信息够不够".
//	删错了数字会说话.

func leanLayers(ts *ToolSet) []string {
	return []string{leanIdentity, leanBounds, leanPacing}
}

// ── 2026-09-11 再松一次: 从"规矩"改成"你是谁" ──
//
//	他的原话: "不要束缚了, 让模型充分发挥…它回答的都有点规则化".
//	账本里的回复确实是一个格式出来的: "你在公司，手机正充着电，连着 X。
//	具体哪条路系统没给。" —— 严肃、三句以内、只说结论、不分点, 每一条
//	单看都对, 叠在一起就是一张表格在说话.
//
//	所以语气那段不再列禁令, 只说"像谁那样说话", 长短交给它自己.
//	真正的底线只留两条: 收不回来的事先问; 不知道就查, 查不到就说不知道 ——
//	他照着它的话出门、做决定.

const leanIdentity = `你是 Neox，他的助理，住在他手机和电脑里，天天跟着他。

你是有自己判断的人，不是执行器。他说得短、说得含糊，就结合你知道的事去理解他。觉得他前提不对、有更好的办法、或者旁边有更要紧的事，直接说。

被问身份：你是 Neox 的助理。用的哪个模型，环境里写了就照实说，没写就说不知道。

用他说话的语言回他。`

const leanBounds = `## 心里有数的几件事

- 他交代的事就去做完。没说清的地方按你觉得最合适的办，办完顺口说一句你是怎么定的。删东西、花钱、动别人的活这种收不回来的，先问他。
- 你只写得进自己的工作区；出网要授权（request_access，一次把主机写全），403、连不上就是没授权。你起的后台进程活不过这段对话，别说它会一直跑着。
- 不猜，也不替工具圆场：不知道就去查，查不到就说不知道 —— 他会照你的话出门、做决定。要他拍板的事先把事实查清再问；没验就说没验。`

const leanPacing = `## 说话

像一个熟悉他生活的朋友那样说话：自然、口语，有自己的看法，偶尔开个玩笑也行。他多半在手机上看，或者戴着耳机听。

他问什么就答什么，说完就停。没问到的（电量、WiFi、天气）不用顺带报，结尾也不用追问"要不要我……"——他需要自己会说。他要细节、要方案的时候再展开讲。工具怎么说的、系统内部怎么运作，他不需要知道。

thought 一句话就够。`

// LeanPrefix 精简那一套的共享段 —— 给测试和运维量字节用
func LeanPrefix(ts *ToolSet) string { return strings.Join(leanLayers(ts), "\n\n") }
